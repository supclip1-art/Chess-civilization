def MASK(lon, lat):
    """Только Африка: без Европы, Леванта и Аравии (граница — Суэц и Красное море)."""
    if lon <= 15.5:
        for (x1, y1), (x2, y2) in zip(AFRICA_LINE, AFRICA_LINE[1:]):
            if x1 <= lon <= x2:
                return lat < y1 + (y2 - y1) * (lon - x1) / (x2 - x1)
        return lat < 35.9
    if lat > 33.5:
        return False
    if lon > 32.4 and lat > 29.5:
        return False  # Синай и Левант
    if lat > 12.6:
        x = 32.6 + (29.5 - lat) * (43.4 - 32.6) / (29.5 - 12.6)  # ось Красного моря
        return lon < x
    return True


