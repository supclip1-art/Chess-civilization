def climate(lon, lat, q, r, noise, smooth_noise):
    # Нил: узкая зелёная полоса через пустыню
    if 29.5 < lat < 31.8 and 30.6 < lon < 32.2:
        return None
    if 15.0 < lat < 29.5 and abs(lon - (31.0 + (29.5 - lat) * 0.15)) < 0.9:
        return None
    for x, y, rx, ry in DESERTS:
        if ((lon - x) / rx) ** 2 + ((lat - y) / ry) ** 2 < 1 - 0.45 * (smooth_noise(q, r, 7) - 0.5):
            return 'desert'
    return None


