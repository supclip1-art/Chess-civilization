def climate(lon, lat, q, r, noise, smooth_noise):
    for x, y, rx, ry in DESERTS:
        d = ((lon - x) / rx) ** 2 + ((lat - y) / ry) ** 2
        if d < 1 - 0.45 * (smooth_noise(q, r, 7) - 0.5):
            return 'desert'
    if lat >= 51.0 and lon > 60 and smooth_noise(q, r, 5) > 0.62:
        return 'tundra'
    return None


